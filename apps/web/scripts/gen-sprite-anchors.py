#!/usr/bin/env python3
"""
Generate per-sprite footprint anchors for the lab plot.

Each isometric building sprite is drawn freely on a 64x64 canvas (gateways via
art/iso.py, economy buildings via art/isobuild.py), so the building's ground
contact is NOT at the image centre and varies per sprite. The renderer needs to
know, per sprite, the point that should sit on a tile — otherwise tall/asymmetric
buildings hang off their tile.

This script reads every rendered PNG's alpha and records the silhouette's
bottom-centre (in SOURCE px): horizontal centre of the opaque bounding box, and
its lowest opaque row. lib/plot.ts places that point on a tile's front vertex.

Run from repo root:  python3 apps/web/scripts/gen-sprite-anchors.py
Re-run whenever building/gateway sprites are (re)generated.
"""
from PIL import Image
import glob, os

ROOT = os.path.join(os.path.dirname(__file__), "..", "public", "sprites")
OUT = os.path.join(os.path.dirname(__file__), "..", "lib", "sprites", "anchors.generated.ts")
GATEWAY_KEYS = ["discovery", "science_fair", "literature_review", "operations_hub",
                "research_plan", "pvp", "showcase"]


def anchor(path):
    im = Image.open(path).convert("RGBA")
    w, h = im.size
    px = im.load()
    minx = miny = 10 ** 9
    maxx = maxy = -1
    for y in range(h):
        for x in range(w):
            if px[x, y][3] > 20:
                minx, maxx = min(minx, x), max(maxx, x)
                miny, maxy = min(miny, y), max(maxy, y)
    return round((minx + maxx) / 2, 1), maxy


def main():
    buildings = {}
    for p in sorted(glob.glob(os.path.join(ROOT, "buildings", "*", "*.png"))):
        lab = os.path.basename(os.path.dirname(p))
        slug = os.path.splitext(os.path.basename(p))[0]
        buildings[f"{lab}/{slug}"] = anchor(p)

    gateways = {}
    for k in GATEWAY_KEYS:
        gateways[k] = anchor(os.path.join(ROOT, "gateways", f"{k}_generic.png"))

    lines = [
        "// AUTO-GENERATED by scripts/gen-sprite-anchors.py — do not edit by hand.",
        "// Footprint anchor per sprite, in SOURCE px: the silhouette's bottom-centre",
        "// (ground-contact point). The plot places this point on a tile's front vertex",
        "// so every building — whatever its size/shape — sits centred on its tile.",
        "",
        "export interface SpriteAnchor { ax: number; ay: number }",
        "",
        "export const BUILDING_ANCHORS: Record<string, SpriteAnchor> = {",
        *[f"  '{k}': {{ ax: {ax}, ay: {ay} }}," for k, (ax, ay) in buildings.items()],
        "}",
        "",
        "export const GATEWAY_ANCHORS: Record<string, SpriteAnchor> = {",
        *[f"  '{k}': {{ ax: {ax}, ay: {ay} }}," for k, (ax, ay) in gateways.items()],
        "}",
        "",
    ]
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}: buildings={len(buildings)} gateways={len(gateways)}")


if __name__ == "__main__":
    main()
