#!/usr/bin/env node
/**
 * Generates lib/sprites/versions.generated.ts — a content hash per sprite PNG.
 *
 * The manifest appends this hash as a `?v=<hash>` cache-bust token, so every sprite
 * URL is content-addressed: redraw a sprite → its bytes change → its hash changes →
 * its URL changes → browsers fetch the fresh art instead of serving a stale copy from
 * the long-lived (immutable) cache. Sprites that DIDN'T change keep their URL and stay
 * cached. This is what lets us cache sprites aggressively without ever going stale.
 *
 * Run automatically by the `build` and `dev` npm scripts (see package.json), so the
 * map always reflects the PNGs currently on disk — you never have to bump it by hand.
 * Defensive: if the sprites dir is missing it writes an empty map rather than failing
 * the build.
 */
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative, dirname, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url)) // apps/web/scripts
const PUBLIC_DIR = join(here, '..', 'public')
const SPRITES_DIR = join(PUBLIC_DIR, 'sprites')
const OUT = join(here, '..', 'lib', 'sprites', 'versions.generated.ts')

/** Recursively collect every .png under a directory (empty if it doesn't exist). */
function walk(dir) {
  const out = []
  let entries
  try {
    entries = readdirSync(dir, { withFileTypes: true })
  } catch {
    return out
  }
  for (const e of entries) {
    const full = join(dir, e.name)
    if (e.isDirectory()) out.push(...walk(full))
    else if (e.isFile() && e.name.endsWith('.png')) out.push(full)
  }
  return out
}

const files = walk(SPRITES_DIR).sort()
const map = {}
for (const f of files) {
  // Key by the public URL path the manifest builds, e.g. /sprites/tiles/grass_1.png
  const url = '/' + relative(PUBLIC_DIR, f).split(sep).join('/')
  map[url] = createHash('sha1').update(readFileSync(f)).digest('hex').slice(0, 10)
}

const body = Object.keys(map)
  .sort()
  .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(map[k])},`)
  .join('\n')

const contents = `// AUTO-GENERATED by scripts/gen-sprite-versions.mjs — do not edit by hand.
// Content hash (sha1, first 10 hex) per sprite PNG. The manifest appends this as a
// ?v=<hash> token so a redrawn sprite gets a NEW URL and browsers fetch fresh art
// instead of a stale immutable-cached copy. Regenerated by the build/dev scripts, so
// it always reflects the PNGs currently on disk.

export const SPRITE_VERSIONS: Record<string, string> = {
${body}
}
`

writeFileSync(OUT, contents)
console.log(`gen-sprite-versions: hashed ${files.length} sprites → ${relative(process.cwd(), OUT)}`)
