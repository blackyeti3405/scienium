#!/usr/bin/env node
/**
 * Generates lib/commit-heatmap.generated.ts — real commit counts per day
 * (YYYY-MM-DD) for roughly the last 12 months, aggregated from `git log`.
 *
 * A STATIC build-time snapshot, never a live GitHub API call — the repo may be
 * private, and the Commits Grid on /about should never depend on reaching
 * GitHub at request time. Mirrors gen-sprite-versions.mjs: run automatically
 * by the `dev`/`build` npm scripts (see package.json), so the map reflects
 * whatever history is on disk when you build. Defensive: if `git` or the repo
 * isn't available, it writes an empty map rather than failing the build.
 */
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { join, dirname, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url)) // apps/web/scripts
const REPO_ROOT = join(here, '..', '..', '..') // pnpm workspace root
const OUT = join(here, '..', 'lib', 'commit-heatmap.generated.ts')
const DAYS = 365

/** Day (YYYY-MM-DD) -> commit count, across all branches, or {} if git fails. */
function commitDayCounts() {
  try {
    const since = new Date(Date.now() - DAYS * 24 * 60 * 60 * 1000).toISOString().slice(0, 10)
    const out = execFileSync(
      'git',
      ['log', '--all', `--since=${since}`, '--date=short', '--pretty=format:%ad'],
      { cwd: REPO_ROOT, encoding: 'utf8' },
    )
    const counts = {}
    for (const line of out.split('\n')) {
      const day = line.trim()
      if (!day) continue
      counts[day] = (counts[day] || 0) + 1
    }
    return counts
  } catch {
    return {}
  }
}

const counts = commitDayCounts()
const body = Object.keys(counts)
  .sort()
  .map((day) => `  ${JSON.stringify(day)}: ${counts[day]},`)
  .join('\n')

const contents = `// AUTO-GENERATED by scripts/gen-commit-heatmap.mjs — do not edit by hand.
// Real commit counts per day (YYYY-MM-DD), last ~12 months, from \`git log --all\`.
// A static build-time snapshot — never a live GitHub API call (the repo may be
// private). Regenerated by the build/dev scripts, so it reflects whatever
// history is on disk at build time.

export const COMMIT_HEATMAP: Record<string, number> = {
${body}
}
`

writeFileSync(OUT, contents)
console.log(
  `gen-commit-heatmap: aggregated ${Object.keys(counts).length} active days → ${relative(process.cwd(), OUT)}`,
)
