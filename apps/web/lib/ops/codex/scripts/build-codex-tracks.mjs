// @ts-check
/**
 * Field Codex track builder.
 *
 * Content is authored as data under `../content/<slug>.json` (one `CodexTrack`
 * per file — see `.claude/codex-pipeline/`). This script emits the compact,
 * typed wrapper module `../tracks/<slug>.ts` for each — a thin re-export that is
 * the code-split boundary `index.ts`'s `loadTrack` imports. The bulk lesson
 * content stays out of TypeScript entirely, so tracks/*.ts are ~10 lines each
 * instead of ~29,000.
 *
 * Because a wrapper's default export IS the parsed JSON, its runtime object is
 * deep-equal to the authored source by construction; the checksum + zod gates in
 * `__tests__/generated-content.test.ts` and the `content-shape.test.ts` invariants
 * are what actually validate the content.
 *
 * Usage:
 *   node build-codex-tracks.mjs           # (re)write every wrapper, then cross-check index.ts
 *   node build-codex-tracks.mjs --check   # verify wrappers are up to date + index is in sync; write nothing
 *
 * Run via `pnpm --filter web codex:build[ -- --check]`. `--check` is the CI-safe
 * mode: it exits non-zero if any wrapper is missing/stale or the registry drifts.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'

const CHECK = process.argv.includes('--check')

const codexDir = fileURLToPath(new URL('../', import.meta.url))
const contentDir = `${codexDir}content/`
const tracksDir = `${codexDir}tracks/`
const indexPath = `${codexDir}index.ts`
const checksumsPath = `${contentDir}.checksums.json`

/**
 * Deterministic JSON with lexicographically sorted keys — a stable fingerprint
 * of a track's data that is independent of key order. `generated-content.test.ts`
 * recomputes this and asserts it matches the committed `.checksums.json`, which
 * locks each track's runtime object to its reviewed snapshot: any content edit
 * that changes the data must be re-built (regenerating this file) on purpose.
 * @param {unknown} value
 * @returns {string}
 */
function stableStringify(value) {
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(',')}]`
  if (value && typeof value === 'object') {
    const keys = Object.keys(value).sort()
    return `{${keys.map((k) => `${JSON.stringify(k)}:${stableStringify(value[k])}`).join(',')}}`
  }
  return JSON.stringify(value)
}

/** @param {string} slug */
function wrapperSource(slug) {
  return `// @generated by lib/ops/codex/scripts/build-codex-tracks.mjs — DO NOT EDIT BY HAND.
// Source of truth: lib/ops/codex/content/${slug}.json
// Regenerate after editing that JSON: pnpm --filter web codex:build
//
// Lazily imported by ../index.ts's loadTrack (the per-track code-split boundary);
// never import a tracks/*.ts module eagerly from panel code. The bulk lesson
// content lives in the co-located JSON, authored via .claude/codex-pipeline/.
import type { CodexTrack } from '../types'
import data from '../content/${slug}.json'

const track = data as unknown as CodexTrack
export default track
`
}

/** All authored content slugs (content/*.json, excluding the checksum sidecar). */
function contentSlugs() {
  return readdirSync(contentDir)
    .filter((f) => f.endsWith('.json') && !f.startsWith('.'))
    .map((f) => f.replace(/\.json$/, ''))
    .sort()
}

/** @param {string[]} slugs */
function crossCheckIndex(slugs) {
  const index = readFileSync(indexPath, 'utf8')
  const loaderSlugs = new Set([...index.matchAll(/'([a-z0-9-]+)':\s*\(\)\s*=>\s*import\('\.\/tracks\//g)].map((m) => m[1]))
  const summarySlugs = new Set([...index.matchAll(/\bslug:\s*'([a-z0-9-]+)'/g)].map((m) => m[1]))

  /** @type {string[]} */
  const problems = []
  for (const slug of slugs) {
    if (!loaderSlugs.has(slug)) problems.push(`content/${slug}.json has no LOADERS entry in index.ts`)
    if (!summarySlugs.has(slug)) problems.push(`content/${slug}.json has no CODEX_TRACKS summary entry in index.ts`)
  }
  for (const slug of loaderSlugs) {
    if (!slugs.includes(slug)) problems.push(`index.ts LOADERS references '${slug}' but content/${slug}.json is missing`)
  }
  return problems
}

function main() {
  const slugs = contentSlugs()
  if (slugs.length === 0) {
    console.error('No content/*.json files found — nothing to build.')
    process.exit(1)
  }

  /** @type {string[]} */
  const stale = []
  /** @type {Record<string, string>} */
  const checksums = {}
  for (const slug of slugs) {
    // Fail fast on unreadable / non-JSON source, and fingerprint the data.
    const data = JSON.parse(readFileSync(`${contentDir}${slug}.json`, 'utf8'))
    checksums[slug] = createHash('sha256').update(stableStringify(data)).digest('hex')

    const target = `${tracksDir}${slug}.ts`
    const expected = wrapperSource(slug)
    const current = existsSync(target) ? readFileSync(target, 'utf8') : null

    if (current === expected) continue
    if (CHECK) {
      stale.push(current === null ? `${slug}.ts is missing` : `${slug}.ts is out of date`)
    } else {
      writeFileSync(target, expected, 'utf8')
      console.log(`${current === null ? 'created' : 'updated'} tracks/${slug}.ts`)
    }
  }

  const expectedChecksums = JSON.stringify(checksums, null, 2) + '\n'
  const currentChecksums = existsSync(checksumsPath) ? readFileSync(checksumsPath, 'utf8') : null
  if (currentChecksums !== expectedChecksums) {
    if (CHECK) {
      stale.push('.checksums.json is out of date')
    } else {
      writeFileSync(checksumsPath, expectedChecksums, 'utf8')
      console.log('updated content/.checksums.json')
    }
  }

  const indexProblems = crossCheckIndex(slugs)

  if (CHECK && (stale.length || indexProblems.length)) {
    console.error('codex:build --check failed:')
    for (const s of stale) console.error(`  - ${s} (run \`pnpm --filter web codex:build\`)`)
    for (const p of indexProblems) console.error(`  - ${p}`)
    process.exit(1)
  }
  if (indexProblems.length) {
    // Registry drift is a real defect even outside --check — surface it loudly.
    console.error('index.ts registry is out of sync with content/:')
    for (const p of indexProblems) console.error(`  - ${p}`)
    process.exit(1)
  }

  console.log(`codex:build ${CHECK ? 'check' : 'done'} — ${slugs.length} track(s): ${slugs.join(', ')}`)
}

main()
